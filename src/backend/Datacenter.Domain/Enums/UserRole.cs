namespace Datacenter.Domain.Enums;

public enum UserRole
{
    /// <summary>ผู้ดูแลระบบ — ทำได้ทุกอย่างรวมถึงประวัติการใช้งาน</summary>
    Admin = 1,

    /// <summary>ผู้บันทึก — บันทึก/นำเข้าข้อมูลของบริษัทที่ดูแล</summary>
    Maker = 2,

    /// <summary>ผู้ตรวจ — ตรวจสอบข้อมูลของบริษัทที่ดูแล</summary>
    Checker = 3,

    /// <summary>
    /// หัวหน้างาน — เหมือน Maker/Checker ในงานรายบริษัท แต่จัดการ "ตั้งค่ากลาง" ได้
    /// (ผู้ใช้งานระบบ, โปรไฟล์สำนักงาน, ทะเบียนผู้สอบ/ผู้ทำบัญชี, ผู้ลงนาม, อัตรา ปกส.)
    /// ยกเว้นประวัติการใช้งาน (audit log) ที่ยังเป็นของ Admin เท่านั้น
    /// </summary>
    Supervisor = 4,
}
